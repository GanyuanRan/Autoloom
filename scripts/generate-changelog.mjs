import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const DEFAULT_REPOSITORY = 'GanyuanRan/Autoloom'
const repository = process.argv[2] ?? process.env.GITHUB_REPOSITORY ?? DEFAULT_REPOSITORY
if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/u.test(repository)) {
  throw new Error(`Invalid repository: ${repository}`)
}

const headers = {
  accept: 'application/vnd.github+json',
  'user-agent': 'autoloom-changelog-generator',
  'x-github-api-version': '2022-11-28',
}
if (process.env.GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.GITHUB_TOKEN}`

async function listReleases() {
  const releases = []
  for (let page = 1; ; page += 1) {
    const response = await fetch(`https://api.github.com/repos/${repository}/releases?per_page=100&page=${page}`, { headers })
    if (!response.ok) throw new Error(`GitHub Releases request failed: HTTP ${response.status}`)
    const batch = await response.json()
    if (!Array.isArray(batch)) throw new Error('GitHub Releases response was not an array')
    releases.push(...batch)
    if (batch.length < 100) return releases
  }
}

function markdownText(value) {
  return String(value).replaceAll('\\', '\\\\').replaceAll('[', '\\[').replaceAll(']', '\\]')
}

function releaseDate(release) {
  const value = release.published_at ?? release.created_at
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}T/u.test(value)) throw new Error(`Release ${release.tag_name} has no valid date`)
  return value.slice(0, 10)
}

function releaseRows(releases, language) {
  return releases
    .filter(release => release && release.draft !== true && typeof release.tag_name === 'string' && release.tag_name.length > 0)
    .map(release => {
      const name = typeof release.name === 'string' && release.name.trim() ? release.name.trim() : release.tag_name
      const url = `https://github.com/${repository}/releases/tag/${encodeURIComponent(release.tag_name)}`
      const status = release.prerelease === true ? language === 'zh' ? '预发布' : 'Pre-release' : language === 'zh' ? '稳定版' : 'Stable'
      return `- [${markdownText(name)}](${url}) — ${releaseDate(release)} — ${status}`
    })
}

function render(releases, language) {
  const english = language === 'en'
  const title = english ? '# Changelog' : '# 版本历史'
  const switcher = english ? 'English | [中文](CHANGELOG.zh-CN.md)' : '[English](CHANGELOG.md) | 中文'
  const introduction = english
    ? 'GitHub Releases are the source of truth for changes, downloads, compatibility notes, and validation scope. This generated index links every published release without copying its release notes.'
    : 'GitHub Releases 是版本变更、下载文件、兼容性说明和验证范围的正式来源。本索引自动生成，只链接所有已发布版本，不复制 Release 说明。'
  const heading = english ? '## Releases' : '## 已发布版本'
  const empty = english ? '_No published releases._' : '_暂时没有已发布版本。_'
  const rows = releaseRows(releases, language)
  return `<!-- Generated by scripts/generate-changelog.mjs. Do not edit by hand. -->\n${title}\n\n${switcher}\n\n${introduction}\n\n${heading}\n\n${rows.length > 0 ? rows.join('\n') : empty}\n`
}

const releases = await listReleases()
const root = dirname(dirname(fileURLToPath(import.meta.url)))
await Promise.all([
  writeFile(join(root, 'CHANGELOG.md'), render(releases, 'en')),
  writeFile(join(root, 'CHANGELOG.zh-CN.md'), render(releases, 'zh')),
])
